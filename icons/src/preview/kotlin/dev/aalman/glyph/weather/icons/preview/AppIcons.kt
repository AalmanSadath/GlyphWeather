package dev.aalman.glyph.weather.icons.preview

import dev.aalman.glyph.weather.icons.Condition
import dev.aalman.glyph.weather.icons.Matrix
import dev.aalman.glyph.weather.icons.WeatherIcons
import java.io.File
import java.util.Locale

/**
 * Writes the toy preview and launcher icon as vector drawables into the app's res/drawable
 * folder (args[0]), drawn from the clear-day icon's still frame.
 *
 * Layout and colours follow Nothing's Phone (3) Glyph preview image specification in the
 * GlyphMatrix Developer Kit: a 512 px black circle, a 440 px matrix inset 36 px, square LEDs
 * 13.05 px wide, #1C1C1C for an unlit LED and #FFFFFF for full brightness.
 */
fun main(args: Array<String>) {
    val out = File(args[0]).apply { mkdirs() }
    val frame = WeatherIcons.animation(Condition.CLEAR_DAY).still

    File(out, "toy_preview.xml").writeText(
        vector(
            size = "100dp",
            viewport = 512,
            comment = "Toy preview in Glyph Toys: the clear-day icon on the matrix. Generated by `./gradlew :icons:appIcons`; don't edit.",
            body = matrixPaths(frame, monochrome = false),
        ),
    )
    // Adaptive icons keep their artwork inside a 66 dp circle in the middle of a 108 dp square.
    File(out, "ic_launcher_foreground.xml").writeText(
        vector(
            size = "108dp",
            viewport = 108,
            comment = "Launcher icon foreground: the toy preview inside the 66 dp safe zone. Generated by `./gradlew :icons:appIcons`; don't edit.",
            body = safeZone(matrixPaths(frame, monochrome = false)),
        ),
    )
    File(out, "ic_launcher_monochrome.xml").writeText(
        vector(
            size = "108dp",
            viewport = 108,
            comment = "Themed launcher icon: lit LEDs only, as alpha. Generated by `./gradlew :icons:appIcons`; don't edit.",
            body = safeZone(matrixPaths(frame, monochrome = true)),
        ),
    )
}

private const val CANVAS = 512.0
private const val INSET = 36.0
private const val PITCH = (CANVAS - 2 * INSET) / Matrix.SIZE
private const val LED = 13.05
private const val UNLIT = 0x1C

private fun matrixPaths(frame: IntArray, monochrome: Boolean): String {
    val byLevel = sortedMapOf<Int, StringBuilder>()
    for (y in 0 until Matrix.SIZE) for (x in 0 until Matrix.SIZE) {
        if (!Matrix.isLed(x, y)) continue
        val v = frame[y * Matrix.SIZE + x]
        if (monochrome && v == 0) continue
        val left = INSET + x * PITCH + (PITCH - LED) / 2
        val top = INSET + y * PITCH + (PITCH - LED) / 2
        byLevel.getOrPut(v) { StringBuilder() }
            .append("M${n(left)},${n(top)}h${n(LED)}v${n(LED)}h${n(-LED)}z")
    }
    val paths = StringBuilder()
    if (!monochrome) {
        paths.append(path("#FF000000", "M256,0a256,256 0,1 1,0 512a256,256 0,1 1,0 -512z"))
    }
    for ((v, data) in byLevel) {
        val colour = if (monochrome) {
            "#%02XFFFFFF".format(v)
        } else {
            val c = UNLIT + v * (0xFF - UNLIT) / 255
            "#FF%02X%02X%02X".format(c, c, c)
        }
        paths.append(path(colour, data.toString()))
    }
    return paths.toString()
}

private fun safeZone(body: String): String {
    val scale = 66.0 / CANVAS
    return """    <group android:translateX="21" android:translateY="21" android:scaleX="${n(scale)}" android:scaleY="${n(scale)}">
$body    </group>
"""
}

private fun path(colour: String, data: String) =
    "        <path android:fillColor=\"$colour\" android:pathData=\"$data\" />\n"

private fun vector(size: String, viewport: Int, comment: String, body: String) = """<?xml version="1.0" encoding="utf-8"?>
<!-- $comment -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="$size"
    android:height="$size"
    android:viewportWidth="$viewport"
    android:viewportHeight="$viewport">
$body</vector>
"""

private fun n(v: Double) = String.format(Locale.ROOT, "%.3f", v).trimEnd('0').trimEnd('.')
